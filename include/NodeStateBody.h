#pragma once

#include <QString>

/// 节点身份状态体（切片 C 立项书 P2 期段一，非 QObject 共享载体）。
///
/// 为什么存在：节点壳是 QObject（随场景父子树生灭），而快照句柄目前持壳裸指针、
/// 壳的存活由墓碑机制保证；立项书 §13.1 的净收益是「壳先亡时状态仍可读」。
/// 身份字段（名字与模块号）先收进本载体：壳持 shared_ptr，快照捕获时再入快照列一份，
/// 于是壳与场景全亡时身份仍可读，快照释放（引用归零）后在本体之外真析构。
///
/// 加锁与否（与立项书 §13.2 对齐）：身份写入面只在停稳期（方案装载 setModuleId /
/// 复制与重命名 setName），与执行读不并发——与拆分前 NodeBase 直接裸读写的并发面
/// 完全一致，共享化不新增写读面，故不加锁；参数内核的锁由 ThreadSafeParams 自带。
/// 成员公开仅为本体（NodeBase 与直写语义的 HalconNode::fromJson）与快照列使用，
/// 外部一律走访问器。
struct NodeStateBody
{
    QString name;
    int moduleId = 0;   ///> 唯一的模块号（单调用点（方案装载）直写，语义与拆分前逐字节同）
};
